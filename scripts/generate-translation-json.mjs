#!/usr/bin/env node
/**
 * Generates public/locales/{locale}/translation.json for all 22 locales.
 * Merges en base + ui-strings + chrome-templates.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { LOCALES } from './i18n-data/constants.mjs';
import { allUiStrings } from './i18n-data/ui-strings.mjs';
import { buildChrome } from './i18n-data/chrome-templates.mjs';
import { sanitizeDeep } from './i18n-data/text-sanitize.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const EN_FILE = path.join(ROOT, 'public', 'locales', 'en', 'translation.json');

function deepMerge(base, overlay) {
	const out = structuredClone(base);
	for (const [key, value] of Object.entries(overlay)) {
		if (value && typeof value === 'object' && !Array.isArray(value) && typeof out[key] === 'object' && out[key]) {
			out[key] = deepMerge(out[key], value);
		} else {
			out[key] = value;
		}
	}
	return out;
}

function uiOverlay(locale, ui) {
	return {
		nav: ui.nav,
		hero: ui.hero,
		trust: ui.trust,
		product: {
			title: ui.product.title,
			addToCart: ui.product.addToCart,
			monthly: ui.product.monthly,
			lifetime: ui.product.lifetime,
			available: ui.product.available,
			gameBadge: ui.product.gameBadge,
			platformBadge: ui.product.platformBadge,
			statusBadge: ui.product.statusBadge,
		},
		reviews: {
			title: ui.reviews.title,
			subtitle: ui.reviews.subtitle,
			outOf: ui.reviews.outOf,
			countLabel: ui.reviews.countLabel,
		},
		common: {
			buyNow: ui.common.buyNow,
			readGuide: ui.common.readGuide,
			language: ui.common.language,
			officialLanguageNote: ui.common.officialLanguageNote,
			relatedPages: ui.common.relatedPages,
		},
		footer: ui.footer,
		images: ui.images,
	};
}

async function main() {
	const enBase = JSON.parse(await readFile(EN_FILE, 'utf8'));

	for (const locale of LOCALES) {
		const ui = allUiStrings[locale];
		if (!ui) throw new Error(`Missing ui strings for ${locale}`);

		const chrome = buildChrome(locale, ui);
		let merged = deepMerge(enBase, uiOverlay(locale, ui));
		merged = deepMerge(merged, chrome);
		merged = sanitizeDeep(merged, locale);

		// Fix legacy broken key if present in base
		if (merged.homeSeo?.['linkLeague of LegendsCheats']) {
			merged.homeSeo.linkLoLCheats = merged.homeSeo['linkLeague of LegendsCheats'];
			delete merged.homeSeo['linkLeague of LegendsCheats'];
		}

		const outDir = path.join(ROOT, 'public', 'locales', locale);
		await mkdir(outDir, { recursive: true });
		await writeFile(path.join(outDir, 'translation.json'), `${JSON.stringify(merged, null, 2)}\n`, 'utf8');
		console.log(`✓ ${locale}/translation.json`);
	}

	// SSR/React catalog with static imports
	const catalogLines = LOCALES.map(
		(l) => `import ${l} from '../../public/locales/${l}/translation.json';`,
	);
	const catalogEntries = LOCALES.map((l) => `\t${l},`).join('\n');
	const catalogBody = `/** Auto-generated by scripts/generate-translation-json.mjs — do not edit. */
${catalogLines.join('\n')}

export const translationCatalogs = {
${catalogEntries}
} as const;

export type TranslationCatalog = typeof en;
`;
	await writeFile(path.join(ROOT, 'src', 'i18n', 'catalog.generated.ts'), catalogBody, 'utf8');
	console.log('✓ src/i18n/catalog.generated.ts');

	console.log(`Generated ${LOCALES.length} locale translation files.`);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
